package com.example.quantum

import com.example.data.model.AssetSpec
import com.example.data.model.QuboParams

object PythonScriptGenerator {

    fun generateFullPythonQiskitScript(
        assets: List<AssetSpec>,
        params: QuboParams
    ): String {
        val tickersList = assets.map { "\"${it.ticker}\"" }.joinToString(", ")
        val muValues = assets.map { String.format("%.4f", it.effectiveExpectedReturn) }.joinToString(", ")

        return """
# ==============================================================================
# Q-Fin Pro: Institutional Hybrid Quantum-Classical Portfolio Optimization
# Generated by Q-Fin Pro Android Institutional Engine
# Stack: Python 3.10+, Qiskit 1.x, qiskit-optimization, scipy, streamlit, yfinance
# ==============================================================================

import numpy as np
import scipy.stats as stats
from scipy.optimize import minimize

# --- 1. QUANTITATIVE INGESTION & COVARIANCE CALIBRATION ---
TICKERS = [$tickersList]
BUDGET = ${params.budgetB}
RISK_AVERSION_Q = ${params.riskAversionQ}
PENALTY_P = ${params.penaltyMultiplierP}

# Transaction Cost & Slippage Parameters
BROKERAGE_BPS = ${params.brokerageFeeBps}
SLIPPAGE_BPS = ${params.slippageBps}
TOTAL_COST_RATE = (BROKERAGE_BPS + SLIPPAGE_BPS) / 10000.0  # in decimal

# Initial portfolio weights (e.g. from existing holdings or 0 for cash)
w_init = np.array([${params.initialWeights.map { String.format("%.4f", it) }.joinToString(", ")}])

# Expected annual return vector (including AI Sentiment Shift overlays)
mu = np.array([$muValues])
n_assets = len(TICKERS)

# Annualized sample covariance matrix
vols = np.array([${assets.map { String.format("%.4f", it.annualVolatility) }.joinToString(", ")}])
corr_matrix = 0.35 * np.ones((n_assets, n_assets)) + 0.65 * np.eye(n_assets)
sigma = np.outer(vols, vols) * corr_matrix

print("Asset Universe:", TICKERS)
print("Expected Returns (mu):", mu)
print(f"Transaction Cost Drag: {BROKERAGE_BPS + SLIPPAGE_BPS:.1f} bps (Brokerage={BROKERAGE_BPS:.1f} bps, Slippage={SLIPPAGE_BPS:.1f} bps)")

# --- 2. QUBO FORMULATION WITH TRANSACTION COST ---
# Objective: min_x  q * x^T Sigma x - mu^T x + TC(x) + P * (sum(x) - B)^2
# TC(x) = c_tx * sum |x_i/B - w_init_i|
# For x_i in {0, 1}: g(x_i) = c_0 + (c_1 - c_0) * x_i
Q = np.zeros((n_assets, n_assets))
const_offset = PENALTY_P * (BUDGET ** 2)
inv_b = 1.0 / BUDGET if BUDGET > 0 else 0.0

for i in range(n_assets):
    c0 = TOTAL_COST_RATE * w_init[i]
    c1 = TOTAL_COST_RATE * abs(inv_b - w_init[i])
    delta_cost = c1 - c0
    const_offset += c0
    for j in range(n_assets):
        if i == j:
            Q[i, i] = RISK_AVERSION_Q * sigma[i, i] - mu[i] + delta_cost + PENALTY_P * (1.0 - 2.0 * BUDGET)
        else:
            Q[i, j] = RISK_AVERSION_Q * sigma[i, j] + PENALTY_P

# --- 3. QUANTUM OPTIMIZATION VIA QISKIT 1.x (QAOA) ---
try:
    from qiskit_optimization import QuadraticProgram
    from qiskit_optimization.algorithms import MinimumEigenOptimizer
    from qiskit_algorithms import QAOA, NumPyMinimumEigensolver
    from qiskit_algorithms.optimizers import COBYLA
    from qiskit.primitives import StatevectorSampler

    # Build QuadraticProgram
    qp = QuadraticProgram(name="Portfolio_QUBO")
    for ticker in TICKERS:
        qp.binary_var(name=ticker)
    
    # Quadratic objective matrix
    qp.minimize(constant=const_offset, linear={}, quadratic={
        (TICKERS[i], TICKERS[j]): float(Q[i, j])
        for i in range(n_assets) for j in range(n_assets)
    })

    # Exact Classical Baseline (NumPyMinimumEigensolver)
    exact_solver = NumPyMinimumEigensolver()
    exact_optimizer = MinimumEigenOptimizer(exact_solver)
    exact_res = exact_optimizer.solve(qp)
    print("\n[Exact Classical Ground State]:")
    print("Optimal Bitstring:", exact_res.x)
    print("Exact Energy:", exact_res.fval)

    # QAOA Execution with COBYLA
    sampler = StatevectorSampler()
    qaoa_solver = QAOA(sampler=sampler, optimizer=COBYLA(maxiter=50), reps=2)
    qaoa_optimizer = MinimumEigenOptimizer(qaoa_solver)
    qaoa_res = qaoa_optimizer.solve(qp)

    print("\n[Quantum QAOA Result]:")
    print("Optimal Bitstring:", qaoa_res.x)
    print("QAOA Energy:", qaoa_res.fval)
    print("Approximation Ratio:", abs(qaoa_res.fval / exact_res.fval if exact_res.fval != 0 else 1.0))

except ImportError:
    print("\nNote: Install Qiskit 1.x with: pip install qiskit qiskit-algorithms qiskit-optimization")
    # Native exact brute-force verification fallback
    best_energy = float('inf')
    best_x = None
    for s in range(1 << n_assets):
        x = np.array([(s >> (n_assets - 1 - i)) & 1 for i in range(n_assets)])
        val = RISK_AVERSION_Q * (x @ sigma @ x) - (mu @ x) + PENALTY_P * (np.sum(x) - BUDGET)**2
        if val < best_energy and np.sum(x) == BUDGET:
            best_energy = val
            best_x = x
    print("\n[Exact Combinatorial Global Minimum]:")
    print("Selected Assets:", [TICKERS[i] for i in range(n_assets) if best_x[i] == 1])
    print("Ground Energy:", best_energy)

# --- 4. STUDENT-T MULTI-ASSET CORRELATED MONTE CARLO ---
print("\n--- Running Correlated Student-t Tail-Risk Engine ---")
nu = 4.5  # Student-t degrees of freedom (leptokurtosis)
L = np.linalg.cholesky(sigma)
N_PATHS = 10000
dt = 90.0 / 252.0  # 90-day horizon

# Portfolio weights (equal weight for selected basket)
w = np.zeros(n_assets)
selected_indices = [i for i in range(min(BUDGET, n_assets))]
for idx in selected_indices:
    w[idx] = 1.0 / len(selected_indices)

# Correlated Student-t draws: X = mu*dt + sqrt(nu / W) * (L_dt * Z)
Z = np.random.normal(size=(N_PATHS, n_assets))
W = np.random.chisquare(df=nu, size=N_PATHS)
L_dt = L * np.sqrt(dt)
scale = np.sqrt(nu / W)[:, np.newaxis]
correlated_returns = (mu * dt) + scale * (Z @ L_dt.T)
portfolio_losses = -(correlated_returns @ w)

var95 = np.percentile(portfolio_losses, 95)
var99 = np.percentile(portfolio_losses, 99)
cvar95 = np.mean(portfolio_losses[portfolio_losses >= var95])
cvar99 = np.mean(portfolio_losses[portfolio_losses >= var99])

print(f"95% Value-at-Risk (VaR): {var95 * 100:.2f}%")
print(f"99% Value-at-Risk (VaR): {var99 * 100:.2f}%")
print(f"95% Conditional VaR (CVaR / Expected Shortfall): {cvar95 * 100:.2f}%")
print(f"99% Conditional VaR (CVaR / Expected Shortfall): {cvar99 * 100:.2f}%")
        """.trimIndent()
    }
}
